#!/usr/bin/env node
/**
 * Writes `.env.development.local` from `supabase status -o env`.
 * Next.js loads this in dev and it overrides `.env.development`.
 * Run after `supabase start` (also hooked from `npm run supabase:start`).
 */
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const outPath = path.join(root, '.env.development.local');

function parseStatusEnv(output) {
  const vars = {};
  for (const line of output.split('\n')) {
    const match = line.match(/^([A-Z_]+)="(.*)"$/);
    if (match) vars[match[1]] = match[2];
  }
  return vars;
}

let vars;
try {
  vars = parseStatusEnv(
    execSync('supabase status -o env', { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }),
  );
} catch {
  console.error('Could not read Supabase status. Start the stack first: npm run supabase:start');
  process.exit(1);
}

if (!vars.API_URL) {
  console.error('Supabase is not running. Start it with: npm run supabase:start');
  process.exit(1);
}

const publishable = vars.PUBLISHABLE_KEY ?? vars.ANON_KEY;

const contents = `# Generated by npm run supabase:env — do not commit (gitignored)
NEXT_PUBLIC_SUPABASE_URL=${vars.API_URL}
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishable}
SUPABASE_SERVICE_ROLE_KEY=${vars.SERVICE_ROLE_KEY ?? ''}
NEXT_PUBLIC_SITE_URL=http://localhost:3000
`;

fs.writeFileSync(outPath, contents);
console.log(`Updated ${path.relative(root, outPath)} for local Supabase.`);
